package opus.core

// Top-level so enum entry initializers can read it before the companion object exists.
private const val PIXEL_GRID_SIZE = 9

/** One nine-pixel grid for every UI symbol. Hosts draw integer cells without filtering. */
enum class PixelIcon(private vararg val rows: String) {
    CHECK(".........", ".........", ".......#.", "......##.", ".#...##..", ".##.##...", "..###....", "...#.....", "........."),
    ARROW_LEFT(".........", "...#.....", "..##.....", ".##......", "########.", ".##......", "..##.....", "...#.....", "........."),
    ARROW_RIGHT(".........", ".....#...", ".....##..", "......##.", ".########", "......##.", ".....##..", ".....#...", "........."),
    CHEVRON_LEFT(".........", ".....#...", "....##...", "...##....", "..##.....", "...##....", "....##...", ".....#...", "........."),
    CHEVRON_RIGHT(".........", "...#.....", "...##....", "....##...", ".....##..", "....##...", "...##....", "...#.....", "........."),
    CHEVRON_UP(".........", ".........", "....#....", "...###...", "..##.##..", ".##...##.", ".#.....#.", ".........", "........."),
    CHEVRON_DOWN(".........", ".........", ".#.....#.", ".##...##.", "..##.##..", "...###...", "....#....", ".........", "........."),
    CALENDAR("..#...#..", ".#######.", ".##...##.", ".#######.", ".#.....#.", ".#.#.#.#.", ".#.....#.", ".#######.", "........."),
    CLOSE(".........", ".##...##.", "..##.##..", "...###...", "....#....", "...###...", "..##.##..", ".##...##.", "........."),
    PLUS(".........", "...##....", "...##....", "...##....", ".######..", ".######..", "...##....", "...##....", "........."),
    SEARCH("..####...", ".##..##..", ".#....#..", ".#....#..", ".##..##..", "..####...", ".....##..", "......##.", ".......#."),
    COIN("..#####..", ".##...##.", "##..#..##", "#..###..#", "#..#.#..#", "#..###..#", "##..#..##", ".##...##.", "..#####.."),
    GRID(".........", ".###.###.", ".#.#.#.#.", ".###.###.", ".........", ".###.###.", ".#.#.#.#.", ".###.###.", "........."),
    CATEGORY(".........", ".###.....", ".#######.", ".#.....#.", ".#.....#.", ".#.....#.", ".#.....#.", ".#######.", "........."),
    EDIT("......##.", ".....###.", "....###..", "...###...", "..###....", ".###.....", ".##......", ".#####...", "........."),
    TRASH("...###...", ".#######.", "..#...#..", "..#.#.#..", "..#.#.#..", "..#.#.#..", "..#...#..", "..#####..", ".........");

    init {
        require(rows.size == PIXEL_GRID_SIZE && rows.all { it.length == PIXEL_GRID_SIZE && it.all { cell -> cell == '.' || cell == '#' } })
    }

    fun pixelAt(x: Int, y: Int): Boolean {
        require(x in 0 until SIZE && y in 0 until SIZE)
        return rows[y][x] == '#'
    }

    companion object {
        const val SIZE = PIXEL_GRID_SIZE
        /** Whole-pixel scale for the allocated box, with the native 9-unit grid as the minimum size. */
        @JvmStatic fun scaleForSize(width: Float, height: Float): Int {
            require(width.isFinite() && height.isFinite() && width >= 0f && height >= 0f)
            return (minOf(width, height) / SIZE).toInt().coerceAtLeast(1)
        }
    }
}
